const assert = require('node:assert/strict');
const activity = require('../js/learning-activity');
const practice = require('../js/practice-sessions');
global.window = global;
require('../js/data/problems/answer-keys.js');
const data = new Map();
global.localStorage = { getItem: key => data.get(key) || null, setItem: (key, value) => data.set(key, value) };
activity.record('learn', 'exposure', 'L1.2', 'opened', 'lesson');
activity.record('flashcards', 'attempt', 'vietas-quadratic', 'good', 'card');
activity.record('quiz', 'attempt', 'vietas-quadratic', 'correct', 'card');
const slug = '2026-amc-12b-19';
const set = practice.create('Practice', 'Any', [slug]);
practice.answer(set, slug, practice.officialKey(slug));
practice.finish(set);
practice.save(localStorage, set);
const history = activity.history({ practice, canonical: () => '2026-amc-10b-24' });
assert.equal(history.length, 5);
assert.equal(history.find(event => event.kind === 'problem').canonicalId, '2026-amc-10b-24');
assert.equal(history.find(event => event.kind === 'problem').outcome, 'correct');
assert.deepEqual(new Set(history.map(event => event.source)), new Set(['practice', 'learn', 'flashcards', 'quiz']));
const saved = JSON.parse(localStorage.getItem(activity.KEY));
assert.equal(activity.merge(saved, saved).events.length, 3, 'reimporting a backup does not duplicate events');
const newer = '{"version":2,"events":[]}';
localStorage.setItem(activity.KEY, newer);
activity.record('quiz', 'attempt', 'vietas-quadratic', 'incorrect', 'card');
assert.equal(localStorage.getItem(activity.KEY), newer);
console.log('Learning activity: shared history, existing practice attempts, canonical problems and repeat imports passed.');
