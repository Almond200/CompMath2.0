const assert = require('node:assert/strict');
const activity = require('../js/learning-activity');
const practice = require('../js/practice-sessions');
global.window = global;
require('../js/data/problems/answer-keys.js');
const data = new Map();
global.localStorage = { getItem: key => data.get(key) || null, setItem: (key, value) => data.set(key, value) };
activity.record('learn', 'exposure', 'L1.2', 'opened', 'lesson');
activity.record('flashcards', 'attempt', 'vietas-quadratic', 'good', 'card');
activity.record('quiz', 'attempt', 'vietas-quadratic', 'correct', 'card');
const slug = '2026-amc-12b-19';
const set = practice.create('Practice', 'Any', [slug]);
practice.answer(set, slug, practice.officialKey(slug));
practice.finish(set);
practice.save(localStorage, set);
async function checkHistory() {
  const history = await activity.history({ practice, canonical: () => '2026-amc-10b-24' });
  assert.equal(history.length, 5);
  assert.equal(history.find(event => event.kind === 'problem').canonicalId, '2026-amc-10b-24');
  assert.equal(history.find(event => event.kind === 'problem').outcome, 'correct');
  assert.deepEqual(new Set(history.map(event => event.source)), new Set(['practice', 'learn', 'flashcards', 'quiz']));
  const saved = JSON.parse(localStorage.getItem(activity.KEY));
  assert.equal(activity.merge(saved, saved).events.length, 3, 'reimporting a backup does not duplicate events');
  const missed = practice.create('Missed', 'Any', [slug]);
  practice.answer(missed, slug, practice.officialKey(slug) === 'A' ? 'B' : 'A');
  practice.finish(missed);
  practice.save(localStorage, missed);
  await activity.saveMistakes('practice', missed.id, slug, ['carelessness','starting']);
  await activity.saveMistakes('arena', 'rated', slug, ['recognition']);
  const legacyMark = JSON.parse(localStorage.getItem(activity.KEY));
  legacyMark.events.find(e => e.type === 'mistake' && e.source === 'practice').outcome = ['accuracy','reading','starting','timing'];
  legacyMark.events.find(e => e.type === 'mistake' && e.source === 'arena').outcome = ['reasoning','timing'];
  localStorage.setItem(activity.KEY, JSON.stringify(legacyMark));
  const arenaState = { events: [{session:'rated', identity:slug, slug, outcome:'correct', firstMiss:'A', at:0}] };
  const problemHistory = await activity.history({kind:'problem', arenaState, arena:{}, practice});
  assert.equal(problemHistory.length, 3, 'annotations do not create additional problem events');
  assert.deepEqual(problemHistory.find(e => e.id === 'practice:' + missed.id + ':' + slug).mistakes, ['starting','carelessness','timing']);
  assert.deepEqual((await activity.mistakesFor('practice', missed.id)).get(slug), ['starting','carelessness','timing']);
  assert.equal(activity.mistakeBoost(['accuracy','reading']), activity.mistakeBoost(['carelessness']));
  assert.deepEqual(activity.mistakeReasons('reasoning'), ['recognition']);
  assert.equal(problemHistory.find(e => e.id === 'practice:' + set.id + ':' + slug).mistakes, undefined);
  assert.deepEqual(problemHistory.find(e => e.source === 'arena').mistakes, ['recognition']);
  assert.equal(problemHistory.find(e => e.source === 'arena').at, 0, 'the attempt keeps its original date');
  const prior = JSON.parse(localStorage.getItem(activity.KEY));
  await activity.saveMistakes('practice', missed.id, slug, []);
  assert.equal((await activity.mistakesFor('practice', missed.id)).size, 0);
  assert.deepEqual((await activity.mistakesFor('arena', 'rated')).get(slug), ['recognition','timing']);
  const cleared = JSON.parse(localStorage.getItem(activity.KEY));
  const oldMark = prior.events.find(e => Array.isArray(e.outcome) && e.outcome.includes('reading'));
  oldMark.at--;
  assert.deepEqual(activity.merge(cleared, prior).events.find(e => e.id === oldMark.id).outcome, [],
    'importing an older backup preserves a cleared reason');
  const newer = '{"version":2,"events":[]}';
  localStorage.setItem(activity.KEY, newer);
  activity.record('quiz', 'attempt', 'vietas-quadratic', 'incorrect', 'card');
  assert.equal(localStorage.getItem(activity.KEY), newer);
  console.log('Learning activity: shared history, existing practice attempts, canonical problems and repeat imports passed.');
}
checkHistory().catch(error => { console.error(error); process.exitCode = 1; });
