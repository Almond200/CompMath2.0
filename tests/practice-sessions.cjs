const assert = require('node:assert/strict');
const P = require('../js/practice-sessions.js');
let raw = null;
const storage = { getItem: () => raw, setItem: (_, value) => { raw = value; } };
const s = P.create('Geometry', 'Any', ['amc', 'aime'], false, 1000);
assert.equal(s.runningSince, null);
assert(P.answer(s, 'amc', 'C', false));
assert(!P.answer(s, 'amc', 'F', false));
assert(P.answer(s, 'aime', '007', true));
assert(!P.answer(s, 'aime', '1000', true));
assert(!P.answer(s, 'aime', '-1', true));
assert(!P.answer(s, 'aime', '1.2', true));
P.checkpoint(s, 9000);
assert.equal(s.elapsed, 0, 'stopwatch off records no elapsed time');
s.current = 1; s.marks.aime = true;
P.save(storage, s);
let loaded = P.read(storage)[0];
assert.equal(loaded.answers.aime, '007');
assert.equal(loaded.current, 1);
assert.equal(loaded.marks.aime, true);
assert.equal(loaded.status, 'paused');
assert.equal(loaded.runningSince, null);
const timed = P.create('Algebra', 'Hard', ['aime'], true, 1000);
P.pause(timed, 65000);
assert.equal(timed.elapsed, 64000);
P.checkpoint(timed, 90000);
assert.equal(timed.elapsed, 64000, 'paused time does not accumulate');
timed.status = 'active'; timed.runningSince = 100000;
P.finish(timed, 106000);
assert.equal(timed.elapsed, 70000);
assert.equal(timed.status, 'finished');
assert(!P.answer(timed, 'aime', '042', true), 'finished answers cannot change');
s.reviews.amc = 'correct';
P.finish(s, 10000); P.save(storage, s); P.save(storage, timed);
assert.equal(P.read(storage).length, 2, 'upsert preserves other sets');
loaded = P.read(storage).find(x => x.id === s.id);
assert.equal(P.result(loaded, 'amc'), 'Correct');
assert.equal(P.result(loaded, 'aime'), 'Not checked', 'no guessed grade');
loaded.reviews.aime = 'revisit';
assert.equal(P.result(loaded, 'aime'), 'Revisit');
assert.equal(P.result(timed, 'aime'), 'Unanswered');
assert.throws(() => P.save({getItem: () => '{bad', setItem(){assert.fail('must not overwrite unreadable history');}}, s));
assert.throws(() => P.save({getItem: () => '[]', setItem(){throw Error('quota');}}, s));
console.log('Practice sessions: persistence, validation, paused clocks, review, and storage failures passed.');
