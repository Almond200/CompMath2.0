// Summaries support Learn navigation and global search without fetching chapter text.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.join(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const files = [...read('index.html').matchAll(/data-group="chapters" src="(js\/data\/learn\/[^"?]+)\?v=\d+"/g)]
  .map(match => match[1]);
const directories = fs.readdirSync(path.join(root, 'js/data/learn'), { withFileTypes: true })
  .filter(entry => entry.isDirectory());
const chaptersOnDisk = directories.flatMap(entry => {
  const dir = 'js/data/learn/' + entry.name;
  return fs.readdirSync(path.join(root, dir)).filter(file => file.endsWith('.js')).map(file => dir + '/' + file);
});
require('node:assert/strict').deepEqual(files.slice().sort(), chaptersOnDisk.sort(),
  'Every chapter must have one versioned entry in the on-demand script template');
const context = vm.createContext({ window: {} });
for (const file of files) vm.runInContext(read(file), context, { filename: file });

const count = set => (set?.exercises?.length || 0) + (set?.problems?.length || 0);
const chapters = Object.entries(context.window.MATH_LEARN || {}).sort(([a], [b]) => a.localeCompare(b));
const summary = {};
for (const [code, chapter] of chapters) {
  const lessons = {};
  for (const [id, lesson] of Object.entries(chapter.lessons || {})) {
    const body = String(lesson.body || '');
    const lead = (body.split(/\n\s*\n/).find(p => p.trim() && !/^\{\{/.test(p.trim())) || '')
      .replace(/\[\[[^\]|]*\|([^\]]*)\]\]/g, '$1').replace(/\[\[([^\]]*)\]\]/g, '$1');
    const cards = lesson.cards || [];
    const mentioned = new Set((lesson.related || []).map(r => r.card));
    for (const match of body.matchAll(/\[\[([\w-]+)(?:\|[^\]]*)?\]\]/g)) mentioned.add(match[1]);
    for (const card of cards) mentioned.delete(card);
    lessons[id] = {
      lead, cards, mentioned: [...mentioned], exercises: lesson.exercises?.length || 0,
      problems: lesson.problems?.length || 0
    };
  }
  summary[code] = {
    lessons, legacyReview: chapter.review?.length || 0,
    review: count(chapter.reviewProblems), challenge: count(chapter.challenge)
  };
}

const output = '// Generated by tools/build-learn-summary.cjs.\nwindow.MATH_LEARN_SUMMARY = {\n' +
  Object.entries(summary).map(([id, data]) => '  ' + JSON.stringify(id) + ': ' + JSON.stringify(data)).join(',\n') + '\n};\n';
const target = path.join(root, 'js/data/learn-summary.js');
if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
  if (process.argv.includes('--check')) {
    console.error('Learn summary is out of date. Run node tools/build-learn-summary.cjs.');
    process.exitCode = 1;
  } else {
    fs.writeFileSync(target, output);
    console.log('Updated Learn summary');
  }
}
