#!/usr/bin/env python3
"""Snapshot LIVE's public Elo-like ratings for problems in this app.

python3 tools/import-live-ratings.py [--cache /tmp/compmath-live-ratings] [--refresh] [--check]
No account or API key is needed. Cache the index and each published band, validate
counts and identities, then match exact contest/year/problem keys. Manual estimates
share the generated file but never override a published LIVE value.
"""
import argparse
import datetime
import json
from pathlib import Path
import re
import tempfile
import time
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
BASE = 'https://live.poshenloh.com/past-contests/difficulty'
OUT = ROOT / 'js/data/problems/difficulty-ratings.js'


def props(page):
    m = re.search(r'<script id="__NEXT_DATA__"[^>]*>(.*?)</script>', page, re.S)
    if not m:
        raise ValueError('LIVE page has no embedded Next data')
    return json.loads(m.group(1))['props']['pageProps']


def fetch(url, cache, refresh):
    if cache.exists() and not refresh:
        return json.loads(cache.read_text())
    req = urllib.request.Request(url, headers={'User-Agent': 'competition-math-reference (personal, non-commercial study app)'})
    with urllib.request.urlopen(req, timeout=30) as response:
        data = props(response.read().decode('utf-8'))
    cache.parent.mkdir(parents=True, exist_ok=True)
    cache.write_text(json.dumps(data))
    time.sleep(.2)
    return data


def slug(ref):
    return re.sub(r'[^a-z0-9]+', '-', re.sub(r',?\s*problem\s+', '-', ref.lower())).strip('-')


def live_key(ref):
    m = re.fullmatch(r'(\d{4})\s+(?:(Spring|Fall)\s+)?(AMC 8|AJHSME|AHSME|AMC 10[AB]?|AMC 12[AB]?|AIME(?: I| II)?), Problem (\d+)', ref)
    if not m:
        return None
    year, season, contest, number = m.groups()
    if contest == 'AHSME':    # the AMC 12's name until 1999; LIVE files it as AMC 12
        return ('amc12', year, int(number))
    if contest in ('AMC 8', 'AJHSME'):
        return ('amc8', year, int(number))
    if contest.startswith('AIME'):
        return ('aime', year + contest[4:].strip(), int(number))
    sitting = contest[6:]
    if season == 'Fall':
        sitting = {'A': 'C', 'B': 'D'}[sitting]
    return (contest[:6].replace(' ', '').lower(), year + sitting, int(number))


def build(index, bands, manual, refs, date):
    ratings = {}
    for band, rows in zip(index['bands'], bands):
        if len(rows) != band['count']:
            raise ValueError('LIVE band count changed during fetch: ' + band['slug'])
        for row in rows:
            key = (row['contest'], row['year'], row['number'])
            elo = row['elo']
            if key in ratings or type(elo) not in (int, float) or not 0 <= elo <= 10000:
                raise ValueError('Invalid or duplicate LIVE rating: ' + str(key))
            if not band['start'] <= elo < band['start'] + 200:
                raise ValueError('Rating outside its source band: ' + str(key))
            ratings[key] = elo
    if len(ratings) != index['totalRated']:
        raise ValueError('LIVE total does not match all bands')
    unknown = set(manual['ratings']) - set(refs)
    if unknown:
        raise ValueError('Manual estimate has unknown problem: ' + str(sorted(unknown)))
    result = {}
    missing = []
    for ref in refs:
        elo = ratings.get(live_key(ref))
        source = 'live'
        if elo is None:
            estimate = manual['ratings'].get(ref)
            elo = estimate[0] if estimate else None
            source = 'manual'
        if elo is None:
            missing.append(ref)
            continue
        if type(elo) not in (int, float) or not 0 <= elo <= 10000:
            raise ValueError('Invalid estimate: ' + ref)
        if slug(ref) in result:
            raise ValueError('Duplicate normalized problem slug: ' + ref)
        result[slug(ref)] = {'elo': elo, 'source': source}
    meta = {'url': BASE, 'retrieved': date, 'sourceCount': len(ratings),
            'liveCount': sum(r['source'] == 'live' for r in result.values()),
            'manualCount': sum(r['source'] == 'manual' for r in result.values()),
            'unrated': missing}
    lines = ['// Generated by tools/import-live-ratings.py; edit manual estimates in tools/manual-difficulty-ratings.json.',
             '// LIVE values are a dated snapshot, not a live network dependency. Manual values are author estimates.',
             'window.MATH_PROBLEM_RATINGS = {', '  "meta": ' + json.dumps(meta, indent=2).replace('\n', '\n  ') + ',', '  "ratings": {']
    lines += ['    ' + json.dumps(k) + ': ' + json.dumps(result[k], separators=(',', ':')) + (',' if i < len(result)-1 else '')
              for i, k in enumerate(sorted(result))]
    lines += ['  }', '};', '']
    return '\n'.join(lines), meta


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache', type=Path, default=Path(tempfile.gettempdir()) / 'compmath-live-ratings')
    parser.add_argument('--refresh', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    index = fetch(BASE, args.cache / 'index.json', args.refresh)
    bands = [fetch(BASE + '/' + b['slug'], args.cache / (b['slug'] + '.json'), args.refresh)['problems'] for b in index['bands']]
    refs = re.findall(r'\bref:\s*"([^"]+)"', (ROOT / 'js/data/problems/problem-db.js').read_text())
    if len(set(refs)) != len(refs):
        raise ValueError('Duplicate app problem references')
    manual = json.loads((ROOT / 'tools/manual-difficulty-ratings.json').read_text())
    # Checking should not change the snapshot's retrieval date.
    old = re.search(r'"retrieved": "([^"]+)"', OUT.read_text()) if args.check and OUT.exists() else None
    date = old.group(1) if old else datetime.datetime.fromtimestamp((args.cache / 'index.json').stat().st_mtime, datetime.timezone.utc).date().isoformat()
    text, meta = build(index, bands, manual, refs, date)
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            raise SystemExit('Stale difficulty ratings; run tools/import-live-ratings.py')
    else:
        OUT.write_text(text)
    print(f"Difficulty ratings: {meta['liveCount']} LIVE, {meta['manualCount']} manual, {len(meta['unrated'])} unrated; {meta['sourceCount']} source records checked.")


if __name__ == '__main__':
    main()
