#!/usr/bin/env python3
"""Import only structured answer keys from LIVE, after matching existing statements.
No hints or solutions are imported. Set MATH_LIVE_CACHE to a writable cache directory.
Run from the repository root; mismatches are reported for manual review, never guessed.
"""
import hashlib
import concurrent.futures, importlib.util, json, os, pathlib, re, subprocess, time, urllib.request
ROOT = pathlib.Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('statements', ROOT / 'tools/fetch-live-statements.py')
imp = importlib.util.module_from_spec(spec); spec.loader.exec_module(imp)
cache = pathlib.Path(imp.CACHE) / 'answer-keys'; cache.mkdir(parents=True, exist_ok=True)
js = "global.window={};const fs=require('fs');for(const f of fs.readdirSync('js/data/problems/statements'))if(f.endsWith('.js'))require('./js/data/problems/statements/'+f);console.log(JSON.stringify(window.MATH_STATEMENTS));"
statements = json.loads(subprocess.check_output(['node', '-e', js], cwd=ROOT, text=True))
reviewed = json.loads((ROOT / 'tools/answer-key-reviewed.json').read_text())
groups = {}
for slug, st in statements.items():
    source = st.get('u','')
    if slug.startswith('2021-fall-amc-10'):
        source = 'https://live.poshenloh.com/past-contests/amc10/2021' + ('C' if '-10a-' in slug else 'D')
    if source.startswith('https://live.poshenloh.com/past-contests/'):
        groups.setdefault(source, []).append((slug, st))
def norm(s):
    # Differences in display wrapping/spacing do not change question or option content.
    s = re.sub(r'\\(?:left|right|quad|qquad|displaystyle|textstyle)\b', '', s)
    s = s.replace('\\dfrac','\\frac').replace('\\tfrac','\\frac')
    return re.sub(r'\s+', '', s)
def fetch(item):
    source, entries = item
    c,y = source.rstrip('/').split('/')[-2:]
    path = cache / (c+'-'+y+'.json')
    if path.exists(): qs = json.loads(path.read_text())
    else:
        req = urllib.request.Request(source, headers={'User-Agent':imp.UA})
        with urllib.request.urlopen(req, timeout=40) as r: page=r.read().decode()
        data=json.loads(re.search(r'<script id="__NEXT_DATA__"[^>]*>(.*?)</script>',page,re.S)[1])['props']['pageProps']
        if data['contest'] != c or str(data['year']) != y: raise ValueError('Wrong paper returned')
        # Cache only the fields needed for answer/statement validation, never solutions.
        qs=[{k:q.get(k) for k in ['question','a','b','c','d','e','answer','answerFillIn']} for q in data['baseQuestions']]
        path.write_text(json.dumps(qs)); time.sleep(.5)
    answers={}; issues=[]
    for slug, st in entries:
        n=int(slug.rsplit('-',1)[1])
        if n>len(qs): issues.append((slug,'missing question'));continue
        q=qs[n-1]; rendered=imp.statement(q,c,y,n,[])
        if norm(rendered)!=norm(st['s']):
            check=reviewed.get(slug,{})
            if check.get('local_sha256')!=hashlib.sha256(st['s'].encode()).hexdigest() or check.get('imported_sha256')!=hashlib.sha256(rendered.encode()).hexdigest() or check.get('answer')!=str(q.get('answer','')).upper():
                issues.append((slug,'statement differs'));continue
        answer=str((q.get('answerFillIn') or q.get('answer')) if c=='aime' else q.get('answer','')).strip().upper()
        if not re.fullmatch(r'\d{1,3}' if c=='aime' else '[A-E]',answer): issues.append((slug,'invalid answer'));continue
        answers[slug]=str(int(answer)) if c=='aime' else answer
    return source,answers,issues
answers={};sources={};issues=[]
with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
    jobs={pool.submit(fetch,item):item[0] for item in groups.items()}
    for i,f in enumerate(concurrent.futures.as_completed(jobs),1):
        try:
            source,a,b=f.result();answers.update(a);issues.extend(b)
            for slug in a: sources[slug.rsplit('-',1)[0]]=source
        except Exception as e: issues.append((jobs[f],str(e)))
        if i%20==0: print(f'{i}/{len(jobs)} papers, {len(answers)} verified answers',flush=True)
# Problems the MAA voided are recorded by hand in the existing file; keep them across a regeneration.
old=(ROOT/'js/data/problems/answer-keys.js').read_text()
m=re.search(r'"voided": (\{.*?\n \})',old,re.S)
output={'answers':dict(sorted(answers.items())),'sources':dict(sorted(sources.items())),'voided':json.loads(m.group(1)) if m else {}}
(ROOT/'js/data/problems/answer-keys.js').write_text('// Structured answers from LIVE by Po-Shen Loh, matched against local statements.\n// Generated by tools/fetch-answer-keys.py; problem copyright MAA, CC BY-NC-SA 4.0.\nwindow.MATH_ANSWER_KEYS = '+json.dumps(output,ensure_ascii=False,indent=1)+';\n')
(cache/'issues.json').write_text(json.dumps(issues,indent=2))
print(f'{len(answers)} answers; {len(issues)} issues. Report: {cache / "issues.json"}',flush=True)
