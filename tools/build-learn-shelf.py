#!/usr/bin/env python3
"""Build js/data/learn/shelf.js from LEARN-OUTLINE.md, so the app's shelf and the outline never drift.

The shelf holds the books (title, role), their chapters (code, title, level) and each chapter's
lesson titles. Lesson content is not here yet; it comes with the lesson files (PLAN step L6).
usage: python3 tools/build-learn-shelf.py           # write the file
       python3 tools/build-learn-shelf.py --check   # fail if the file is out of date, or a chapter file
                                                     # breaks a rule (tools/check-learn.js; gates.sh)
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC, OUT = ROOT / "LEARN-OUTLINE.md", ROOT / "js/data/learn/shelf.js"
IDS = {"AMC → AIME Bridge": "bridge", "AIME Algebra": "aime-algebra", "AIME Number Theory": "aime-number-theory",
       "AIME Geometry": "aime-geometry", "AIME Counting & Probability": "aime-counting"}

def build():
    text = SRC.read_text()
    roles = {m[1]: m[2].strip() for m in re.finditer(r"^\| \*\*(.+?)\*\* \| (.+?) \| [BANGC]\d", text, re.M)}
    books, book, chapter = [], None, None
    for line in text.splitlines():
        m = re.match(r"^## Book: (.+)$", line)
        if m:
            title = m[1].strip()
            book = {"id": IDS[title], "title": title, "role": roles.get(title, ""), "chapters": []}
            books.append(book)
            chapter = None
            continue
        m = re.match(r"^### ([BANGC]\d)\. (.+?) \((Core II|Core|Extension)\b[^)]*\)(?::.*)?$", line)
        if m and book:
            chapter = {"code": m[1], "title": m[2].strip(), "level": m[3], "lessons": []}
            book["chapters"].append(chapter)
            continue
        m = re.match(r"^\| ([BANGC]\d\.\d) ([^|]+?) \|", line) or re.match(r"^#### ([BANGC]\d\.\d) (.+)$", line)
        if m and chapter and m[1].startswith(chapter["code"] + "."):
            chapter["lessons"].append({"code": m[1], "title": m[2].strip()})
    return ("// Generated by tools/build-learn-shelf.py from LEARN-OUTLINE.md; do not edit by hand.\n"
            "// The Learn shelf: books, their chapters (Core, Core II or Extension) and lesson titles.\n"
            "window.MATH_LEARN_SHELF = " + json.dumps(books, ensure_ascii=False, indent=1) + ";\n")

out = build()
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != out:
        sys.exit("FAIL - js/data/learn/shelf.js is out of date: run python3 tools/build-learn-shelf.py")
    print("OK - the Learn shelf matches LEARN-OUTLINE.md")
    # The chapter files: cards, problems placed once, check answers that parse (CONVENTIONS §14).
    import subprocess
    if subprocess.run(["node", str(ROOT / "tools/check-learn.js")]).returncode:
        sys.exit(1)
else:
    OUT.write_text(out)
    print("wrote", OUT.relative_to(ROOT))
