#!/usr/bin/env python3
"""Build js/data/curriculum/shelf.js (window.MATH_CURRICULUM_SHELF) from curriculum/data/index.json.

The preview shelf lists every book, chapter and concept section of the new curriculum, and which
chapters are written: a chapter is written when js/data/curriculum/<book-id>/<code>.js exists,
for example geometry-2/g2.02.js for G2.2.

usage: python3 tools/curriculum/build-shelf.py [--check]
"""
import json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
idx = json.loads((ROOT / "curriculum/data/index.json").read_text(encoding="utf-8"))
OUTDIR = ROOT / "js/data/curriculum"
def code_file(book, cid):
    a, b = cid.split(".")
    return OUTDIR / book / f"{a.lower()}.{int(b):02d}.js"
books, written = [], []
for b in idx["books"]:
    chs = []
    for c in b["chapters"]:
        chs.append({"id": c["id"], "title": c["title"], "status": c["status"], "sections": [{"id": s["id"], "title": s["title"]} for s in c["sections"]]})
        if code_file(b["id"], c["id"]).exists(): written.append(b["id"] + "/" + c["id"])
    title = b["title"].split(" — ")[0]
    books.append({"id": b["id"], "prefix": b["prefix"], "title": title, "subtitle": b["title"].split(" — ")[1] if " — " in b["title"] else "", "chapters": chs})
js = ("// Generated by tools/curriculum/build-shelf.py from curriculum/data/index.json; do not edit by hand.\n"
      "window.MATH_CURRICULUM_SHELF = " + json.dumps({"books": books, "written": written}, ensure_ascii=False, indent=1) + ";\n")
out = OUTDIR / "shelf.js"
if "--check" in sys.argv:
    ok = out.exists() and out.read_text(encoding="utf-8") == js
    print("curriculum shelf", "up to date" if ok else "STALE"); sys.exit(0 if ok else 1)
out.write_text(js, encoding="utf-8"); print("written:", written)
